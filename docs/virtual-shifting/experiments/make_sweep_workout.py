#!/usr/bin/env python3
"""Build the experiment-17 workout bundle + a console installer from the sweep route.

The app has no "import workout" UI — only Save Current / Load / Delete against localStorage —
and a saved workout stores `routeName` only, NOT the route's geoPoints (`SavedWorkoutEntry`,
src/types.ts:81-86). So "one JSON with the climb in it" is not a native shape. This emits:

  17-crr-cw-sweep-workout.json   bundle: {route, workout} — each member byte-for-byte the shape
                                 the app already reads (`garminRoute`, `SavedWorkoutEntry`)
  17-install-sweep-workout.js    paste-into-console installer with the bundle inlined, so there
                                 is no fetch path to get wrong and no 8-step click-through

Regenerate the route first (`make_sweep_route.py > 17-crr-cw-sweep-route.json`), then run this.
Usage: python3 make_sweep_workout.py
"""

import json
import pathlib

HERE = pathlib.Path(__file__).parent
ROUTE_PATH = HERE / "17-crr-cw-sweep-route.json"
BUNDLE_PATH = HERE / "17-crr-cw-sweep-workout.json"
INSTALLER_PATH = HERE / "17-install-sweep-workout.js"

WORKOUT_NAME = "Crr/Cw Sweep — 6 laps"

# 6 SIM steps = 6 laps: runWorkoutStep resets simDistanceTraveled per SIM step
# (src/js/main.js:1281-1285) and auto-advances 5 s after route completion, so the laps chain
# without intervention and each one emits its own `step` event for the analysis to split on.
LAPS = 6

# ERG steps. Duration is MINUTES and may be fractional (ErgStep, src/types.ts:26-30).
# Deliberately modest: the measurement blocks want a warm rider, not a tired one, and lap 1 is
# a baseline condition whose whole job is to be comparable with laps 3 and 6.
WARMUP = {"type": "erg", "duration": 5, "power": 120}
COOLDOWN = {"type": "erg", "duration": 5, "power": 100}

# A REST step sits between every pair of laps so the whole protocol is ONE continuous workout.
#
# Without it the rider must stop and press Start Workout again for each condition, and every
# Start Workout calls startRideLog — which used to clear the log, exporting six ridden laps as
# one. That is now archived rather than lost (rideLog.ts), but a single uninterrupted run is
# still far better: one clock, one file, no chance of a forgotten export. 90 s is unhurried time
# to work two dropdowns and the Apply button. Nothing here is analysed.
REST = {"type": "erg", "duration": 1.5, "power": 100}


def main() -> None:
    route = json.loads(ROUTE_PATH.read_text())

    lap = {"type": "sim", "segmentName": route["name"]}
    plan = [WARMUP]
    for i in range(LAPS):
        plan.append(dict(lap))
        # The last lap's rest is the cool-down.
        plan.append(dict(COOLDOWN) if i == LAPS - 1 else dict(REST))

    bundle = {
        "bundleVersion": 1,
        "name": WORKOUT_NAME,
        "notes": (
            "Experiment 17 — Crr/Cw sweep. Six laps of a constant-grade route, tyre/position "
            "changed between laps on an A-B-A-C-D-A schedule. Hold gear 12 (index 11, ratio "
            "2.40) and ~85 rpm on the two 0% blocks; shift freely elsewhere. Protocol: "
            "17-crr-cw-sweep-protocol.md"
        ),
        # Exactly what the Import Garmin Route textarea accepts, and what storage.ts persists
        # under the `garminRoute` key.
        "route": route,
        # Exactly a SavedWorkoutEntry, except savedAt which the installer stamps — scripts here
        # must stay deterministic so the generated files don't churn in git on every run.
        "workout": {
            "name": WORKOUT_NAME,
            "plan": plan,
            "routeName": route["name"],
            "savedAt": None,
        },
    }
    BUNDLE_PATH.write_text(json.dumps(bundle, indent=1) + "\n")

    installer = f"""// Experiment 17 — install the Crr/Cw sweep route + workout. Paste into the app's console.
//
// Generated by make_sweep_workout.py — edit that, not this. Writes the four localStorage keys
// the app reads (storage.ts:20-33), then reloads so the legacy boot path picks them up: it
// reads route and plan once at startup (main.js loadRoute/loadWorkoutPlan), so setting them
// without a reload would leave the UI and H.state disagreeing.
;(async () => {{
  const bundle = {json.dumps(bundle, indent=2)}

  const w = {{ ...bundle.workout, savedAt: Date.now() }}
  localStorage.setItem('garminRoute', JSON.stringify(bundle.route))
  localStorage.setItem('workoutPlan', JSON.stringify(w.plan))
  localStorage.setItem('savedWorkout_' + w.name, JSON.stringify(w))
  const index = JSON.parse(localStorage.getItem('savedWorkoutsIndex') || '[]')
  if (!index.includes(w.name)) index.push(w.name)
  localStorage.setItem('savedWorkoutsIndex', JSON.stringify(index))

  console.log(
    `[17] installed "${{w.name}}": ${{w.plan.length}} steps ` +
      `(${{w.plan.filter((s) => s.type === 'sim').length}} laps of ${{bundle.route.name}}, ` +
      `${{bundle.route.totalDistance}} m each). Reloading…`
  )
  location.reload()
}})()
"""
    INSTALLER_PATH.write_text(installer)

    sim_steps = sum(1 for s in plan if s["type"] == "sim")
    print(f"{BUNDLE_PATH.name}: {len(plan)} steps ({sim_steps} laps), route {route['name']}")
    print(f"{INSTALLER_PATH.name}: {INSTALLER_PATH.stat().st_size} bytes")


if __name__ == "__main__":
    main()
